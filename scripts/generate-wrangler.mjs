import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const getEnv = (key, defaultValue = '') => process.env[key] || defaultValue;

const workerName = getEnv('WORKER_NAME', 'cf-link-redirect');
const kvNamespaceId = getEnv('KV_NAMESPACE_ID', 'placeholder_kv_id');
const analyticsDataset = getEnv('ANALYTICS_DATASET', 'LINK_REDIRECT_ANALYTICS');
const customDomain = getEnv('CUSTOM_DOMAIN', '');
const adminToken = getEnv('ADMIN_TOKEN', 'change_this_secret_token');
const defaultFallbackUrl = getEnv('DEFAULT_FALLBACK_URL', '');
const siteName = getEnv('SITE_NAME', 'Link Redirect Gateway');
const accountId = getEnv('CLOUDFLARE_ACCOUNT_ID', '');

let content = `# Generated automatically by scripts/generate-wrangler.mjs
# DO NOT EDIT THIS FILE DIRECTLY - Edit environment variables or wrangler.toml.template

name = "${workerName}"
main = "src/index.ts"
compatibility_date = "2024-11-01"
compatibility_flags = ["nodejs_compat"]
`;

if (accountId) {
  content += `account_id = "${accountId}"\n`;
}

content += `
# KV Namespace Binding
[[kv_namespaces]]
binding = "LINKS_KV"
id = "${kvNamespaceId}"
`;

// Optional Analytics Engine binding
if (analyticsDataset) {
  content += `
# Analytics Engine Binding
[[analytics_engine_datasets]]
binding = "ANALYTICS"
dataset = "${analyticsDataset}"
`;
}

// Optional Custom Domain Route
if (customDomain) {
  const pattern = customDomain.includes('/*') ? customDomain : (customDomain.endsWith('/') ? `${customDomain}*` : `${customDomain}/*`);
  content += `
# Custom Domain Routes
routes = [
  { pattern = "${pattern}", custom_domain = true }
]
`;
}

content += `
# Public / App Environment Variables
[vars]
ADMIN_TOKEN = "${adminToken}"
DEFAULT_FALLBACK_URL = "${defaultFallbackUrl}"
SITE_NAME = "${siteName}"
`;

const outputPath = path.join(projectRoot, 'wrangler.toml');
fs.writeFileSync(outputPath, content.trim() + '\n', 'utf-8');
console.log(`[OK] wrangler.toml successfully generated at: ${outputPath}`);
